#!/usr/bin/env python3
"""Verify (or regenerate) src/data/marketingSpendData.ts from its source JSON.

The Marketing Spend calculator's reference tables are a static extract of one file,
`Marketing_Spend_Pct_Revenue_37_Industries.json` (RefractOne Market Intelligence).
Same failure mode as the IT/ERD tables: a re-issued source file that never gets
re-extracted ships stale numbers silently. This script makes that drift loud:

    python3 scripts/marketing-spend-data.py            # report drift, exit 1 if stale
    python3 scripts/marketing-spend-data.py --write    # regenerate the TS file

It also re-derives every industry's published per-tier and per-region figures
(`by_revenue_tier`, `by_hq_region`) from the global multipliers the calculator uses,
and refuses to extract if they disagree — so a source file whose multipliers no
longer explain its own tables can't be shipped by accident.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

DEFAULT_SOURCE = Path.home() / "Desktop" / "Marketing_Spend_Pct_Revenue_37_Industries.json"
DATA_FILE = Path(__file__).resolve().parent.parent / "src" / "data" / "marketingSpendData.ts"
YEARS = [str(y) for y in range(2022, 2031)]
TOLERANCE = 1e-4  # source shares are rounded to 6 dp; reconstruction error is ~4e-6


def r6(x: float) -> float:
    return round(float(x), 6)


def check_multipliers(src: dict) -> list[str]:
    """Rebuild by_revenue_tier / by_hq_region from the global multipliers."""
    tax = {t["code"]: t for t in src["taxonomy"]}
    tiers = src["revenue_tiers"]["tiers"]
    elasticity = src["revenue_tiers"]["archetype_elasticity"]
    tier_l2 = src["revenue_tiers"]["l2_mix_multipliers"]
    regions = {r["region"]: r for r in src["hq_regions"]}
    problems: list[str] = []

    def l1_shares(weights: dict[str, float]) -> dict[str, float]:
        total = sum(weights.values())
        out: dict[str, float] = {}
        for code, w in weights.items():
            out[tax[code]["l1"]] = out.get(tax[code]["l1"], 0.0) + w / total
        return out

    for ind in src["industries"]:
        name = ind["industry"]
        base = ind["l3_by_year"]["2025"]
        e = elasticity[ind["archetype"]]
        for i, t in enumerate(tiers):
            published = ind["by_revenue_tier"][t["tier"]]
            mult = 1 + (t["base_intensity_multiplier"] - 1) * e
            if abs(mult - published["intensity_multiplier"]) > TOLERANCE:
                problems.append(f"{name} / {t['tier']}: intensity {mult} != {published['intensity_multiplier']}")
            mix = l1_shares({c: v["share"] * tier_l2[tax[c]["l2_key"]][i] for c, v in base.items()})
            for l1, share in published["l1_share"].items():
                if abs(mix[l1] - share) > TOLERANCE:
                    problems.append(f"{name} / {t['tier']} / {l1}: mix {mix[l1]:.6f} != {share}")
        for region_name, region in regions.items():
            published = ind["by_hq_region"][region_name]
            if abs(region["intensity_multiplier"] - published["intensity_multiplier"]) > TOLERANCE:
                problems.append(f"{name} / {region_name}: intensity mismatch")
            l2 = region["l2_mix_multipliers"]
            mix = l1_shares({c: v["share"] * l2.get(tax[c]["l2_key"], 1.0) for c, v in base.items()})
            for l1, share in published["l1_share"].items():
                if abs(mix[l1] - share) > TOLERANCE:
                    problems.append(f"{name} / {region_name} / {l1}: mix {mix[l1]:.6f} != {share}")
    return problems


def render(src: dict) -> str:
    taxonomy = [
        {"code": t["code"], "level1": t["l1"], "level2": t["l2"], "l2Key": t["l2_key"], "level3": t["l3"]}
        for t in src["taxonomy"]
    ]
    codes = [t["code"] for t in src["taxonomy"]]
    industries = {
        ind["industry"]: {
            "archetype": ind["archetype"],
            "archetypeName": ind["archetype_name"],
            "goToMarket": ind["go_to_market"],
            "pctRevenue": [r6(ind["pct_revenue"][y]) for y in YEARS],
            # l3Share[yearIdx][taxonomyIdx] — share of the total marketing budget
            "l3Share": [[r6(ind["l3_by_year"][y][c]["share"]) for c in codes] for y in YEARS],
        }
        for ind in src["industries"]
    }
    tiers = [{"tier": t["tier"], "multiplier": t["base_intensity_multiplier"]} for t in src["revenue_tiers"]["tiers"]]
    regions = {
        r["region"]: {"intensity": r["intensity_multiplier"], "l2Mix": r["l2_mix_multipliers"]}
        for r in src["hq_regions"]
    }
    def dump(value) -> str:
        return json.dumps(value, ensure_ascii=False, separators=(", ", ": "))

    lines = [
        "// Static reference data for the Marketing Spend calculator — no live API calls.",
        "// GENERATED by scripts/marketing-spend-data.py from",
        "// ~/Desktop/Marketing_Spend_Pct_Revenue_37_Industries.json. Do not hand-edit:",
        "// re-run the script with --write when the source file is re-issued.",
        "//",
        "// Units are fractions (0.077 = 7.7%). pctRevenue is the industry's marketing budget",
        "// as a share of revenue for a $1B-$5B, US-headquartered firm (the base case);",
        "// l3Share[yearIdx][taxonomyIdx] is each Level-3 line's share of that budget.",
        "//",
        f"// Source: {src['meta']['title']} — {src['meta']['publisher']}, built {src['meta']['built']}.",
        f"// Base case: {src['meta']['base_definition']}.",
        *[f"//   - {source}" for source in src['meta']['sources']],
        "// (Kept in comments, not string literals: promptRecency.test.ts flags year literals.)",
        "",
        "export interface MarketingTaxonomyItem { code: string; level1: string; level2: string; l2Key: string; level3: string }",
        "export interface MarketingIndustryRow { archetype: string; archetypeName: string; goToMarket: string; pctRevenue: number[]; l3Share: number[][] }",
        "export interface MarketingTierRow { tier: string; multiplier: number }",
        "export interface MarketingRegionRow { intensity: number; l2Mix: Record<string, number> }",
        "",
        f"export const MARKETING_YEARS: number[] = {dump([int(y) for y in YEARS])};",
        "",
        f"export const MARKETING_TAXONOMY: MarketingTaxonomyItem[] = {dump(taxonomy)};",
        "",
        "/** 7 revenue tiers (<$25M … >$10B), base intensity multiplier before archetype elasticity. */",
        f"export const MARKETING_REVENUE_TIERS: MarketingTierRow[] = {dump(tiers)};",
        "",
        "/** How strongly each archetype reacts to the tier multiplier: m = 1 + (tierMult - 1) * elasticity. */",
        f"export const MARKETING_ARCHETYPE_ELASTICITY: Record<string, number> = {dump(src['revenue_tiers']['archetype_elasticity'])};",
        "",
        "/** Per-L2 mix multipliers by revenue tier (7 entries, tier order) — reweights the budget mix, then renormalized. */",
        f"export const MARKETING_TIER_L2_MIX: Record<string, number[]> = {dump(src['revenue_tiers']['l2_mix_multipliers'])};",
        "",
        "/** 16 HQ regions: intensity multiplier on % of revenue, plus L2 mix multipliers (missing key = 1). */",
        f"export const MARKETING_HQ_REGIONS: Record<string, MarketingRegionRow> = {dump(regions)};",
        "",
        f"export const MARKETING_ARCHETYPES: Record<string, string> = {dump(src['archetypes'])};",
        "",
        f"export const MARKETING_INDUSTRIES: Record<string, MarketingIndustryRow> = {dump(industries)};",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--write", action="store_true", help="regenerate the TS file from the source JSON")
    args = parser.parse_args()

    if not args.source.is_file():
        print(f"source file not found: {args.source}", file=sys.stderr)
        return 2
    src = json.loads(args.source.read_text(encoding="utf-8"))

    problems = check_multipliers(src)
    if problems:
        print(f"source multipliers do not reproduce its own tables ({len(problems)} mismatches):", file=sys.stderr)
        for p in problems[:20]:
            print("  " + p, file=sys.stderr)
        return 3

    expected = render(src)
    current = DATA_FILE.read_text(encoding="utf-8") if DATA_FILE.exists() else ""

    if args.write:
        DATA_FILE.write_text(expected, encoding="utf-8")
        print(f"wrote {DATA_FILE.name} ({'changed' if expected != current else 'unchanged'})")
        return 0
    if expected != current:
        print(f"{DATA_FILE.name} is stale against {args.source.name} (re-run with --write)")
        return 1
    print(f"{DATA_FILE.name} matches {args.source.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
